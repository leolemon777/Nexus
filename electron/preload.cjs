contextBridge.exposeInMainWorld("nexusDesktop", {
  platform: process.platform,
  invoke(command, args = {}) {
    if (!allowedCommands.has(command)) {
      return Promise.reject(new Error(`不允许调用桌面命令：${command}`));
    }
    return ipcRenderer.invoke(`nexus:${command}`, args);
  },
  onPollData(callback) {
    const handler = (_event, data) => callback(data);
    ipcRenderer.on("nexus:poll_data", handler);
    return () => ipcRenderer.removeListener("nexus:poll_data", handler);
  },
  onPollError(callback) {
    const handler = (_event, error) => callback(error);
    ipcRenderer.on("nexus:poll_error", handler);
    return () => ipcRenderer.removeListener("nexus:poll_error", handler);
  },
  onDebugFrame(callback) {
    const handler = (_event, record) => callback(record);
    ipcRenderer.on("nexus:debug_frame", handler);
    return () => ipcRenderer.removeListener("nexus:debug_frame", handler);
  },
  onScanProgress(callback) {
    const handler = (_event, progress) => callback(progress);
    ipcRenderer.on("nexus:scan_progress", handler);
    return () => ipcRenderer.removeListener("nexus:scan_progress", handler);
  },
});
